// Copies the compiled Place ABI into the frontend as a typed `as const` module.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const { abi } = JSON.parse(readFileSync(`${root}contracts/out/Place.sol/Place.json`, 'utf8'))
writeFileSync(
  `${root}web/src/abi.ts`,
  `// Generated by scripts/export-abi.mjs — do not edit.\nexport const placeAbi = ${JSON.stringify(abi, null, 2)} as const\n`,
)
console.log(`wrote web/src/abi.ts (${abi.length} entries)`)
